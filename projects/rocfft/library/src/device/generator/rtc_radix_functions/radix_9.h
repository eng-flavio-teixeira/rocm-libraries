// real sine part:
//     t_k = x_k + x_(p-k),  u_k = x_k - x_(p-k),   k = 1..4
//     out_0 = x0 + sum_k t_k
//     m_j   = x0 + sum_k cos(2 pi j k / 9) t_k
//     v_j   =      sum_k sin(2 pi j k / 9) u_k
//     out_j = m_j -+ i v_j,   out_(9-j) = m_j +- i v_j
// The pairing and the final recombination are radix-2 butterflies on disjoint
// register pairs, so they need no temporary: writing the difference first lets
