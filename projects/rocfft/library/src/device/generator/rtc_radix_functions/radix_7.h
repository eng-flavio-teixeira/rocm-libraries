// Radix-7 butterfly, evaluated in place.
//
// Pairing x_k with x_(p-k) splits the transform into a real cosine part and a
// real sine part:
//     t_k = x_k + x_(p-k),  u_k = x_k - x_(p-k),   k = 1..3
//     out_0 = x0 + sum_k t_k
//     m_j   = x0 + sum_k cos(2 pi j k / 7) t_k
//     v_j   =      sum_k sin(2 pi j k / 7) u_k
//     out_j = m_j -+ i v_j,   out_(7-j) = m_j +- i v_j
// The pairing and the final recombination are radix-2 butterflies on disjoint
// register pairs, so they need no temporary: writing the difference first lets
// the sum be recovered as 2*a - (a-b).  The two dense real matrices are applied
// by LU, upper factor top-down and lower factor bottom-up, which has the same
// property -- each sweep only ever reads rows it has not yet overwritten.
//
// The pivot order is chosen to keep the multipliers small (max 1.94 here);
// the natural order is algebraically valid but loses roughly a decimal digit.
// Measured single-precision error is 1.8x float epsilon.


