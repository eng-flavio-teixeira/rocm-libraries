// Two implementations of the radix-7 butterfly, selected at code generation
// time by ROCFFT_INPLACE_RADIX.
//
// The default form materialises its results in temporaries and copies them
// back.  That costs registers but leaves the subexpressions independent, so
// the scheduler has plenty to overlap.
//
// The in-place form below rewrites the inputs in place.  It needs far fewer
// registers -- enough to change occupancy, and to stop spilling for the large
// radices -- but each step reads a register the previous step just wrote, so
// it offers the scheduler much less to work with.  Which one wins depends on
// whether the kernel is short of registers or short of latency to hide, so
// the choice is left to the tuner rather than being made here.
//
// Generated by .agent/analysis/h8_gen_inplace.py -- edit that, not this.

